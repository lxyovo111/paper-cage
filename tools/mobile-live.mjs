import { launch } from './cdp.mjs';
import fs from 'node:fs';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const p = await launch({ port: 9319, dir: 'C:\\Users\\lcj\\Desktop\\tap\\six-rules\\tools\\edge-mlive', w: 390, h: 844, scale: 3 });
const errs = [];
p.on(m => { if (m.method === 'Runtime.exceptionThrown') errs.push('EXC ' + (m.params.exceptionDetails.text||'')); });
await p.send('Page.enable'); await p.send('Runtime.enable');
await p.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 3, mobile: true });
await p.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
await p.send('Emulation.setUserAgentOverride', { userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1' });
await p.send('Page.navigate', { url: 'https://modelscope.cn/studios/lxyovo/six-rules' });
await sleep(14000);
const h = await p.send('Runtime.evaluate', { expression: 'JSON.stringify({t:document.title, w:innerWidth, h:innerHeight, sh:document.documentElement.scrollHeight, ifr:[...document.querySelectorAll("iframe")].map(f=>{const r=f.getBoundingClientRect();return [f.src.slice(0,80), Math.round(r.x), Math.round(r.y), Math.round(r.width), Math.round(r.height)]})})', returnByValue: true });
console.log('TOP', h.result.value);
const s1 = await p.send('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('tools/m-live-top.png', Buffer.from(s1.data, 'base64'));
await p.send('Runtime.evaluate', { expression: 'window.scrollTo(0, document.documentElement.scrollHeight)', returnByValue: true });
await sleep(1200);
const s2 = await p.send('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('tools/m-live-scrolled.png', Buffer.from(s2.data, 'base64'));
console.log('ERRS', errs.slice(0,4).join(' | '));
p.ws.close(); p.proc.kill();