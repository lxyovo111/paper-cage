import { launch, sleep } from './cdp.mjs';
const p = await launch();
await p.init();
await p.goto('http://127.0.0.1:7861/dist/index.html?seed=21&llm=0&speed=1');
await sleep(900);
await p.shot('tools/q1-start.png');
await p.ev('(()=>{document.querySelector("[data-act=write]").dispatchEvent(new MouseEvent("click",{bubbles:true}));})()');
await sleep(300);
await p.ev('(()=>{const t=document.querySelector("#rtxt"); t.value="夜里任何人不得离开自己的房间"; t.dispatchEvent(new Event("input",{bubbles:true})); document.querySelector("[data-k=compile]").dispatchEvent(new MouseEvent("click",{bubbles:true}));})()');
await sleep(700);
await p.shot('tools/q2-compiled.png');
await p.ev('(()=>{document.querySelector("[data-k=ok]").dispatchEvent(new MouseEvent("click",{bubbles:true}));})()');
await sleep(400);
await p.ev('(()=>{document.querySelector("[data-act=night]").dispatchEvent(new MouseEvent("click",{bubbles:true}));})()');
await sleep(350);
await p.ev('(()=>{const b=document.querySelector("[data-k=skip]"); if(b) b.dispatchEvent(new MouseEvent("click",{bubbles:true}));})()');
await sleep(1500);
await p.shot('tools/q3-night.png');
await sleep(2400);
await p.shot('tools/q4-night-report.png');
await p.close();
