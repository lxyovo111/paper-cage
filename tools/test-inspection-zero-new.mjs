import { connect } from './browser.mjs';
import { sleep } from './cdp.mjs';
const b = await connect();
const ev = b.ev;
const click = async (sel) => ev('(()=>{const el=document.querySelector(' + JSON.stringify(sel) + '); if(!el) return false; el.dispatchEvent(new MouseEvent("click",{bubbles:true})); return true;})()');
await b.goto('http://127.0.0.1:7861/dist/index.html?seed=8&llm=0&speed=0.05&intro=0', 1600);
const setup = await ev(`(()=>{
  const g = window.__game.g; g.day = 5; g.ap = 3;
  const r = window.__game.E.writeRule(g, '医务室的窗，任何时候都不许碰。');
  if (!r.ok) return 'write failed';
  g.ap = 0; window.__game.wroteToday = false;
  return {rules:g.rules.length, day:g.day, ap:g.ap};
})()`);
console.log('setup=', JSON.stringify(setup));
await ev('window.__game.askNight()');
await sleep(250);
console.log('nightBlocked=', await ev('JSON.stringify({sheet:!!document.querySelector(".sheet"), toast:(document.querySelector(".toast")||{}).textContent})'));
await click('.slot[data-slot="1"]');
await sleep(300);
console.log('editor=', await ev('JSON.stringify({title:(document.querySelector(".sheet h3")||{}).textContent, sub:(document.querySelector(".sheet .sub")||{}).textContent, val:(document.querySelector("#rtxt")||{}).value})'));
await ev('(()=>{const t=document.querySelector("#rtxt"); t.value="放风区的墙，任何时候都不许碰。"; t.dispatchEvent(new Event("input",{bubbles:true}));})()');
await click('[data-k="compile"]');
await sleep(350);
console.log('verdict=', await ev('JSON.stringify({title:(document.querySelector(".sheet h3")||{}).textContent, free:(document.querySelector(".sheet")||{}).innerText.includes("不扣行动力")})'));
await click('[data-k="ok"]');
await sleep(500);
console.log('after=', await ev('JSON.stringify({rules:window.__game.g.rules.length, ap:window.__game.g.ap, wroteToday:window.__game.wroteToday, sheet:!!document.querySelector(".sheet")})'));
await ev('window.__game.askNight()');
await sleep(300);
console.log('night=', await ev('JSON.stringify({title:(document.querySelector(".sheet h3")||{}).textContent, preds:document.querySelectorAll(".sheet .chip[data-k=pred]").length})'));
b.close();